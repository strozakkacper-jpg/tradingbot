def trade(id, order, side, amount, price, ts, symbol="BTC/USDT"):
    return {"id": id, "order": order, "symbol": symbol, "side": side, "amount": amount,
            "price": price, "cost": amount * price, "timestamp": ts}


def test_group_trades_merges_fills():
    orders = group_trades([trade("1", "A", "buy", 0.1, 100, 10), trade("2", "A", "buy", 0.1, 110, 11),
                           trade("3", "B", "sell", 0.05, 120, 20)])
    assert [o.id for o in orders] == ["A", "B"]
    assert orders[0].amount == pytest.approx(0.2)
    assert orders[0].price == pytest.approx(105)


def test_leader_fractions_reconstructs_balances():
    # lider miał 1000 USDT: kupił za 200 (20%), potem sprzedał połowę BTC
    buy = LeaderOrder("A", "BTC/USDT", "buy", 2.0, 200.0, 100.0, 1)
    sell = LeaderOrder("B", "BTC/USDT", "sell", 1.0, 110.0, 110.0, 2)
    now = {"USDT": 1000 - 200 + 110, "BTC": 1.0}
    (o1, f1), (o2, f2) = leader_fractions([sell, buy], now)
    assert (o1.id, o2.id) == ("A", "B")
    assert f1 == pytest.approx(0.2)
    assert f2 == pytest.approx(0.5)


def test_follower_buy_respects_limit_and_multiplier():
    s = follower_order("buy", 0.2, 2.0, quote_free=1000, base_free=0, price=50, max_trade_quote=300, min_cost=5)
    assert s.cost == pytest.approx(300) and s.amount == pytest.approx(6)
    s = follower_order("buy", 0.8, 2.0, quote_free=100, base_free=0, price=50, max_trade_quote=None, min_cost=5)
    assert s.cost == pytest.approx(100)  # nigdy więcej niż 100% salda


def test_follower_sell_not_limited_and_min_cost():
    s = follower_order("sell", 1.0, 1.0, quote_free=0, base_free=10, price=100, max_trade_quote=50, min_cost=5)
    assert s.amount == pytest.approx(10) and s.skip_reason is None
    s = follower_order("buy", 0.001, 1.0, quote_free=1000, base_free=0, price=100, max_trade_quote=50, min_cost=5)
    assert s.skip_reason


class FakeMarket:
    def __init__(self, price):
        self.p = price

    async def price(self, symbol):
        return self.p

    async def min_cost(self, symbol):
        return 5.0

    async def has(self, symbol):
        return True

    exchange_id = "binance"


def test_paper_copy_end_to_end(tmp_path):
    cfg = Config(bot_token="x", encryption_key=Fernet.generate_key().decode(), db_path=str(tmp_path / "t.db"))
    db = DB(cfg.db_path)
    db.create_leader("T", "manual", None, "active")
    for uid in (1, 2, 3):
        db.ensure_user(uid, None, 1000, "USDT")
        db.update_user(uid, accepted=1, approved=1, active=1, max_trade=1000)
        db.follow(uid, 1, True)
    db.update_user(2, multiplier=2.0)
    db.update_user(3, active=0)
    sent = []

    async def notify(uid, text):
        sent.append(uid)

    market = FakeMarket(100.0)
    eng = CopyEngine(cfg, db, Vault(cfg.encryption_key), market, notify)

    res = asyncio.run(eng.copy(LeaderOrder("A", "BTC/USDT", "buy", 0, 0, 100, 1), 0.25, 1))
    # 3 ma wyłączone kopiowanie ⏸ – nie dostaje ani kopii, ani powiadomienia o ruchu kopiowanego tradera
    assert res["filled"] == 2 and not res.get("alert") and sorted(sent) == [1, 2]
    b1, b2 = db.paper_balances(1), db.paper_balances(2)
    assert b1["USDT"] == pytest.approx(750) and b1["BTC"] == pytest.approx(2.5 * 0.999)
    assert b2["USDT"] == pytest.approx(500)
    assert db.paper_balances(3) == {"USDT": 1000}

    market.p = 120.0
    res = asyncio.run(eng.copy(LeaderOrder("B", "BTC/USDT", "sell", 0, 0, 120, 2), 1.0, 1))
    assert res["filled"] == 2
    sent.clear()
    assert "BTC" not in db.paper_balances(1)
    assert db.paper_balances(1)["USDT"] == pytest.approx(750 + 2.5 * 0.999 * 120 * 0.999)
    assert db.history(1)[0]["status"] == "filled"


